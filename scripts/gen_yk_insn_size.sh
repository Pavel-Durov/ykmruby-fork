#!/usr/bin/env bash
# Extract the instruction-size tables from the compiler's codegen.c into src/yk_insn_size.h.

set -euo pipefail

src=mrbgems/mruby-compiler/src/codegen.c
out=src/yk_insn_size.h

# The tables sit between "#define Z 1" and the next function, mrc_prev_pc.
first='^#define Z 1$'
after='^static const mrc_code'
code=$(sed -n "/$first/,/$after/{/$after/!p}" "$src")

# Make them MRB_YK_STATIC and read the opcode list from core instead of the gem.
code=${code//'static uint8_t mrc_insn_size'/'MRB_YK_STATIC const uint8_t mrc_insn_size'}
code=${code//'"mrc_ops.h"'/'<mruby/ops.h>'}

{
  echo '// Generated by scripts/gen_yk_insn_size.sh from $src.'
  echo '// Do not edit.'
  echo
  echo '#include <stdint.h>'
  echo
  echo "$code"
  echo '#undef Z'
  echo '#undef S'
  echo '#undef W'
} > "$out"
